// The rule for a word, as a sentence, or '' when there is none
export function ruleOf(w) {
  if (!w[3]) return '';
  return w[3] === 'comp' ? `${RULES.comp}: ${w[4]} → ${w[1]} ${w[0]}.` : RULES[w[3]];
}

// The word of a day ('YYYY-MM-DD'): every word comes once before any repeats (a step coprime with the list length)
export function wordOfDay(day) {
  const n = Math.round(Date.parse(day + 'T12:00:00Z') / 86400000);
  let step = 37;
  while (gcd(step, WORDS.length) !== 1) step++;
  return WORDS[((n * step) % WORDS.length + WORDS.length) % WORDS.length];
}
function gcd(a, b) { return b ? gcd(b, a % b) : a; }
